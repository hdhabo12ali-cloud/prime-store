function renderBanners() {
  const strip = document.querySelector("[data-banners-grid]");
  if (!strip) return;
  const banners = catalog.banners || [];
  if (!banners.length) {
    strip.style.display = "none";
    return;
  }
  strip.style.display = "";
  strip.innerHTML = banners.map((b) => {
    const img = `<img src="${escapeHtml(b.imageUrl)}" alt="${escapeHtml(b.title || "")}" loading="lazy" />`;
    return b.linkUrl
      ? `<a class="banner-item" href="${escapeHtml(b.linkUrl)}" target="_blank" rel="noreferrer noopener">${img}</a>`
      : `<div class="banner-item">${img}</div>`;
  }).join("");
}

