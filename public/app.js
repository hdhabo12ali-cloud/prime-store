function packageSummary(pkg) {
  return (pkg.details || "")
    .split(/\n+/)
    .map((line) => line.replace(/^\*+|\*+$/g, "").trim())
    .filter((line) => line && !/^\d+[-.]/.test(line) && !line.includes("البوتات المتوفرة") && !line.includes("اخيرا حابين نعلن"))
    .slice(0, 3)
    .join("\n\n");
}

function featureList(item) {
  const skip = /^(مميزات|النظام يشمل|features|البوتات المتوفرة)/i;
  return (item.features || []).filter((line) => {
    if (!line || skip.test(line)) return false;
    if (item.bots && /^\d+[-.)]/.test(line)) return false;
    return line.length > 8;
  }).slice(0, 10);
}

function mediaSource(item) {
  if ((item.videos && item.videos.length) || (item.images && item.images.length)) return item;
  for (const bot of item.bots || []) {
    const product = productById[bot.id];
    if (product && ((product.videos && product.videos.length) || (product.images && product.images.length))) return product;
  }
  return item;
}

function isLocalMedia(url) {
  return typeof url === "string" && url.startsWith("assets/");
}

function renderMedia(host, item) {
  const source = mediaSource(item);
  const videos = (source.videos || []).filter(isLocalMedia);
  host.innerHTML = "";
  if (videos[0]) {
    const video = document.createElement("video");
    video.controls = true;
    video.muted = true;
    video.defaultMuted = true;
    video.volume = 0;
    video.playsInline = true;
    video.preload = "metadata";
    video.src = videos[0];
    video.addEventListener("volumechange", () => {
      video.muted = true;
      video.volume = 0;
    });
    video.addEventListener("error", () => {
      host.innerHTML = `<img src="${PLACEHOLDER_IMAGE}" alt="">`;
    });
    host.appendChild(video);
    return;
  }
  host.innerHTML = `<img src="${PLACEHOLDER_IMAGE}" alt="">`;
}

function openOverlay(kind, id) {
  if (!overlay) return;
  const item = kind === "package"
    ? catalog.packages.find((pkg) => pkg.id === id)
    : productById[id];
  if (!item) return;

  lastFocus = document.activeElement;
  overlay.querySelector("[data-overlay-kicker]").textContent = t(kind === "package" ? "overlay_package" : "overlay_product");
  overlay.querySelector("[data-overlay-title]").textContent = item.name;
  overlay.querySelector("[data-overlay-prices]").innerHTML = priceBlocks(item);
  overlay.querySelector("[data-overlay-summary]").textContent = kind === "package" ? packageSummary(item) : (item.summary || "");

  const featuresHost = overlay.querySelector("[data-overlay-features]");
  featuresHost.innerHTML = "";
  if (kind !== "package") {
    featureList(item).forEach((line) => {
      const li = document.createElement("li");
      li.textContent = line;
      featuresHost.appendChild(li);
    });
  }

  const botsWrap = overlay.querySelector("[data-overlay-bots]");
  const botsList = overlay.querySelector("[data-overlay-bot-list]");
  if (kind === "package" && item.bots && item.bots.length) {
    botsWrap.hidden = false;
    botsList.innerHTML = item.bots
      .filter((bot) => productById[bot.id])
      .map((bot) => `<button type="button" data-open-bot="${escapeHtml(bot.id)}">${escapeHtml(bot.name)}</button>`)
      .join("");
  } else {
    botsWrap.hidden = true;
    botsList.innerHTML = "";
  }

  renderMedia(overlay.querySelector("[data-overlay-media]"), item);
  overlay.hidden = false;
  body.classList.add("overlay-open");
  overlayClose?.focus();
}

function closeOverlay() {
  if (!overlay || overlay.hidden) return;
  const video = overlay.querySelector("video");
  if (video) video.pause();
  overlay.hidden = true;
  body.classList.remove("overlay-open");
  if (lastFocus && typeof lastFocus.focus === "function") lastFocus.focus();
}

function bindCatalog() {
  refreshCatalog();
  document.addEventListener("click", (event) => {
    const packBtn = event.target.closest("[data-open-package]");
    if (packBtn) {
      const card = packBtn.closest("[data-project]");
      if (card) openOverlay("package", card.dataset.project);
      return;
    }
    const productBtn = event.target.closest("[data-open-product]");
    if (productBtn) {
      openOverlay("product", productBtn.dataset.openProduct);
      return;
    }
    const botBtn = event.target.closest("[data-open-bot]");
    if (botBtn) {
      openOverlay("product", botBtn.dataset.openBot);
      return;
    }
    const filterBtn = event.target.closest("[data-filter]");
    if (filterBtn) {
      activeProductFilter = filterBtn.dataset.filter;
      renderFilters();
      renderProducts();
      return;
    }
    if (event.target.closest("[data-overlay-close]") || event.target === overlay) closeOverlay();
  });
  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape") closeOverlay();
  });
}

