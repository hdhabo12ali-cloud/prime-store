async function initMemberAuth() {
  const wrap = document.querySelector("[data-member-auth]");
  if (!wrap) return;
  const btn = wrap.querySelector("[data-member-login-btn]");
  const menu = wrap.querySelector("[data-member-menu]");

  btn.addEventListener("click", (e) => {
    if (btn.dataset.loggedIn === "true") return; // logged-in click handled separately below
    e.stopPropagation();
    menu.hidden = !menu.hidden;
  });
  document.addEventListener("click", (e) => {
    if (!wrap.contains(e.target)) menu.hidden = true;
  });

  try {
    const res = await fetch("/api/auth/me");
    const data = await res.json();
    if (data && data.user) renderLoggedInMember(wrap, btn, menu, data.user);
  } catch {
    // صامت — يبقى زر "تسجيل الدخول" الافتراضي
  }
}

function renderLoggedInMember(wrap, btn, menu, user) {
  btn.dataset.loggedIn = "true";
  btn.innerHTML = user.avatarUrl
    ? `<img alt="" class="member-avatar" src="${user.avatarUrl}"/>`
    : `<span class="member-avatar member-avatar-fallback">${(user.username || "?").slice(0, 1).toUpperCase()}</span>`;
  menu.innerHTML = `
    <div class="member-menu-name">${user.username || ""}</div>
    <a class="member-menu-item" href="/account"><span>الإعدادات</span></a>
    <a class="member-menu-item" href="/api/auth/logout"><span data-i18n="member_logout">${translations[root.lang].member_logout}</span></a>
  `;
  btn.addEventListener("click", (e) => {
    e.stopPropagation();
    menu.hidden = !menu.hidden;
  });
}

